-- Korak 0.4 — Shema baze
-- Tablice za županije, naselja, cjenik (materijali + klase), narudžbe, stavke i fotografije.
-- Pravilo: prijavljeni korisnici (admin) smiju sve, anonimni ništa.
-- Javni upis narudžbe kasnije ide isključivo preko servera (service role).

-- =====================================================================
-- Enumi (popisi dopuštenih vrijednosti)
-- =====================================================================

create type public.status_narudzbe as enum ('nova', 'potvrdjena', 'realizirana', 'otkazana');

create type public.dio_dana as enum ('jutro', 'popodne', 'svejedno');

create type public.razlog_otkaza as enum (
  'lazna_narudzba',
  'kupac_odustao',
  'ne_javlja_se',
  'premala_kolicina',
  'izvan_podrucja',
  'ostalo'
);

-- =====================================================================
-- Lokacije
-- =====================================================================

create table public.zupanije (
  id integer generated by default as identity primary key,
  naziv text not null unique,
  -- true = Vedran dolazi u ovu županiju i narudžba je dopuštena
  pokrivena boolean not null default false
);

create table public.naselja (
  id integer generated by default as identity primary key,
  naziv text not null,
  opcina text not null,
  zupanija_id integer not null references public.zupanije (id) on delete restrict,
  postanski_broj text,
  lat numeric(9, 6) check (lat between -90 and 90),
  lng numeric(9, 6) check (lng between -180 and 180)
);

create index naselja_zupanija_id_idx on public.naselja (zupanija_id);

-- =====================================================================
-- Cjenik
-- =====================================================================

create table public.materijali (
  id integer generated by default as identity primary key,
  naziv text not null,
  slug text not null unique,
  redoslijed integer not null default 0,
  aktivan boolean not null default true
);

create table public.klase (
  id integer generated by default as identity primary key,
  materijal_id integer not null references public.materijali (id) on delete restrict,
  naziv text not null,
  -- kratki opis po kojem kupac sam prepoznaje klasu
  opis text not null default '',
  cijena_po_kg numeric(10, 2) not null check (cijena_po_kg >= 0),
  aktivna boolean not null default true,
  azurirano timestamptz not null default now(),
  unique (materijal_id, naziv)
);

create index klase_materijal_id_idx on public.klase (materijal_id);

-- =====================================================================
-- Narudžbe
-- =====================================================================

create table public.narudzbe (
  -- id stvara korak uploada fotografija (1.4) i služi kao zaštita od dvostrukog slanja
  id uuid primary key default gen_random_uuid(),
  -- redni broj za ljude, npr. 2026-0042; puni ga okidač dodijeli_broj_narudzbe
  broj text not null unique,
  status public.status_narudzbe not null default 'nova',

  -- kontakt
  ime_prezime text not null check (length(trim(ime_prezime)) > 0),
  -- uvijek u obliku +3859…, normalizira se u format.ts
  mobitel text not null check (mobitel ~ '^\+385[0-9]{8,9}$'),

  -- lokacija
  naselje_id integer not null references public.naselja (id) on delete restrict,
  ulica text not null,
  lat numeric(9, 6) check (lat between -90 and 90),
  lng numeric(9, 6) check (lng between -180 and 180),

  -- termin: dan je tip date, točan dogovoreni trenutak timestamptz
  zeljeni_datum date not null,
  dio_dana public.dio_dana not null default 'svejedno',
  dogovoreni_termin timestamptz,

  -- napomene
  napomena_kupca text,
  napomena_interna text,
  razlog_otkaza public.razlog_otkaza,

  -- iznosi: procjena iz trenutka narudžbe, stvarno tek nakon vaganja
  procjena_ukupno numeric(10, 2) not null check (procjena_ukupno >= 0),
  stvarno_ukupno numeric(10, 2) check (stvarno_ukupno >= 0),

  -- izvor i privola
  privola_at timestamptz not null,
  utm_source text,
  utm_campaign text,
  fbclid text,

  -- vremena
  created_at timestamptz not null default now(),
  potvrdjena_at timestamptz,
  realizirana_at timestamptz,

  -- otkazana narudžba uvijek ima razlog, a ostale ga nemaju
  constraint otkazana_ima_razlog check ((status = 'otkazana') = (razlog_otkaza is not null))
);

create index narudzbe_naselje_id_idx on public.narudzbe (naselje_id);
create index narudzbe_status_created_at_idx on public.narudzbe (status, created_at desc);

create table public.stavke (
  id bigint generated by default as identity primary key,
  narudzba_id uuid not null references public.narudzbe (id) on delete cascade,

  -- prijavljeno (cijena se kopira iz cjenika u trenutku narudžbe)
  klasa_id integer not null references public.klase (id) on delete restrict,
  kg_prijavljeno numeric(10, 2) not null check (kg_prijavljeno > 0),
  cijena_kg_prijavljena numeric(10, 2) not null check (cijena_kg_prijavljena >= 0),

  -- stvarno (upisuje se pri realizaciji)
  klasa_stvarna_id integer references public.klase (id) on delete restrict,
  kg_stvarno numeric(10, 2) check (kg_stvarno >= 0),
  cijena_kg_stvarna numeric(10, 2) check (cijena_kg_stvarna >= 0),
  iznos_stvarni numeric(10, 2) check (iznos_stvarni >= 0)
);

create index stavke_narudzba_id_idx on public.stavke (narudzba_id);
create index stavke_klasa_id_idx on public.stavke (klasa_id);
create index stavke_klasa_stvarna_id_idx on public.stavke (klasa_stvarna_id);

create table public.fotografije (
  id bigint generated by default as identity primary key,
  narudzba_id uuid not null references public.narudzbe (id) on delete cascade,
  -- putanja u bucketu fotografije, npr. narudzbe/{id}/1.jpg
  putanja text not null unique,
  created_at timestamptz not null default now()
);

create index fotografije_narudzba_id_idx on public.fotografije (narudzba_id);

-- Pomoćna tablica: zadnji dodijeljeni redni broj narudžbe po godini.
create table public.brojaci_narudzbi (
  godina integer primary key,
  zadnji_broj integer not null
);

-- =====================================================================
-- Okidači
-- =====================================================================

-- Dodjeljuje broj narudžbe u obliku GGGG-NNNN (godina po zoni Europe/Zagreb).
-- Brojač se povećava atomski (insert ... on conflict), pa dvije istodobne
-- narudžbe ne mogu dobiti isti broj. Svake godine brojanje kreće od 0001.
create function public.dodijeli_broj_narudzbe()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_godina integer := extract(year from (new.created_at at time zone 'Europe/Zagreb'))::integer;
  v_redni integer;
begin
  insert into public.brojaci_narudzbi (godina, zadnji_broj)
  values (v_godina, 1)
  on conflict (godina) do update
    set zadnji_broj = public.brojaci_narudzbi.zadnji_broj + 1
  returning zadnji_broj into v_redni;

  -- najmanje 4 znamenke; nakon 9999 broj samo nastavlja (10000, 10001…)
  new.broj := v_godina::text || '-' || lpad(v_redni::text, greatest(4, length(v_redni::text)), '0');
  return new;
end;
$$;

create trigger narudzbe_dodijeli_broj
before insert on public.narudzbe
for each row execute function public.dodijeli_broj_narudzbe();

-- Pri svakoj izmjeni klase bilježi vrijeme izmjene.
create function public.postavi_azurirano()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.azurirano := now();
  return new;
end;
$$;

create trigger klase_postavi_azurirano
before update on public.klase
for each row execute function public.postavi_azurirano();

